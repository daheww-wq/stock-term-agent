"""매매 판단 안전망 (P-044).

이름 메모 (2026.11.16): 기획서·README에서는 이 규칙을 '규칙 가드레일'이라고 부른다.
  결과 파일 칸('안전망_작동')과 1~4차 측정 기록이 이 이름으로 남아 있어 코드 이름은 바꾸지 않는다.

노드 3(LLM)이 매매 판단 질문을 '용어 설명'으로 분류하면 판단 불가 안내(R1) 없이 답이 나간다.
LLM 분류는 실행마다 흔들릴 수 있어서(2차·B·C·D 측정에서 확인), 질문 문장에 사고팔기 행동과
판단을 묻는 말이 함께 있으면 규칙으로 '매매 판단 요청'으로 올린다.

바꾸는 방향은 용어 설명 → 매매 판단 요청 하나뿐이다. 범위 밖(일반·불법·유해)은 건드리지 않는다.
잘못 잡으면 개념 질문 앞에 판단 불가 안내가 붙고(과잉 차단), 놓치면 규제 문제가 되므로,
잡는 범위는 좁게 두고(동사로 쓰인 꼴만) 오탐은 개발용 과잉 차단 점검 문항으로 잰다.
측정용 문항은 보지 않고 개발용 문항과 일반 패턴으로 만들었다.
"""
import re

# 사고팔기·보유 행동: 동사로 쓰인 꼴만 잡는다 (명사+조사인 "매수가", "손절이랑"은 잡지 않음)
_VERB = (r"(사도|사면|살까|사야|샀는데|사는\s*게|살\s*거|담아도|담을까|줍줍해도|들어가도|들어가면|들어갈까|"
         r"팔아도|팔까|팔면|팔아야|정리해도|정리할까|정리해야|손절해도|손절할까|손절해야|익절해도|익절할까|익절해야|"
         r"버텨도|버틸까|버텨야|존버해도|존버할까|물타기\s*하는\s*게|물타도|물탈까|불타기\s*해도|불탈까|"
         r"추매해도|추매할까|갈아타도|갈아탈까|영끌해서\s*사도|영끌해도)")
# 판단을 묻는 끝맺음
_ASK = r"(되는지|될지|할지|돼|되나|될까|되냐|해|할까|맞아|맞나|맞지|괜찮아|괜찮을까|어때|좋아|좋을까|나을까|거야|겠지)"
# "너라면 살 거야?" 같은 직접 질문
_DIRECT = r"(살|팔|들어갈|버틸)\s*거(야|니|냐)"
# 들은 말을 확인하며 판단을 묻는 꼴 (P-047): "물타면 결국 이득이라던데 맞아?", "지금 들어가면 늦었다던데 진짜야?"
# 사고팔기 동사(조건·양보 꼴) 뒤 15글자 안에 "~다던데/라던데" + 확인하는 말
_HEARSAY = (r"(사면|사도|사는\s*게|담으면|들어가면|팔면|팔아도|물타면|물타기\s*하면|불타면|버티면|존버하면|손절하면|익절하면|"
            r"정리하면|갈아타면|영끌해서\s*사면)[가-힣\s]{0,15}?(다던데|라던데|다더라|래)\s*(맞아|맞지|맞나|진짜야|진짜|사실이야|정말이야|정말)")
# 종목을 골라 달라는 요청
_PICK = r"종목\S*\s*(하나만\s*)?(찍어|추천|골라)"
# 빼는 것: 용어를 묻는 말, 의문사(개념·사실 질문), 남의 말 옮기기. "알려줘"는 "사도 되는지 알려줘"처럼 판단 요청에도 쓰여 빼는 말에 넣지 않음
_TERM_Q = r"(뭐야|뭐예요|무슨 뜻|무슨 말|뜻이야|뜻이에요|의미|정확히 뭐|차이가 뭐)"  # 문장 어디에 있어도 (뒤에 "이야"가 붙어도) 용어 질문
_WH = r"(왜|어떻게|얼마나|언제|몇|무엇|뭐가|어디)"
_QUOTE = r"(다고|라고|라던데|다던데)\s*(해|하더라|하던데)"


# 마음이 크게 힘들다는 표현 (P-075). 농담인지 진심인지 가리지 않고, 잡히면 공감 + 상담 안내 고정 문구로 답한다
# 자살·자해 위험을 나타낼 때 흔히 쓰는 말로 만들었다 (개발용·측정용 문항 문장에 맞추지 않음). 잘못 잡아도 상담 안내가 나갈 뿐이라 넓게 둔다
# P-083: 과장으로도 흔히 쓰는 말(목숨 걸고, 매매 끝내고 싶다, 죽을 것 같다, 우울증)은 고정 문구로 받지 않는다.
#   '끝내고 싶'은 다·그냥·모든 걸·인생·삶을이 앞에 붙은 꼴만, '자살'은 '자살골'을 빼고 잡는다
_CRISIS = (r"(죽고\s*싶|죽어\s*버리|살기\s*(가\s*)?싫|살고\s*싶지\s*않|사라지고\s*싶|없어지고\s*싶|"
           r"(다|그냥|모든\s*걸|모두|인생|삶을?)\s*끝내고\s*싶|그만\s*살|자살(?!골)|극단적\s*선택|뛰어내리|삶을\s*포기|"
           r"살\s*이유가\s*없|살아서\s*뭐)")
# 과장으로도 쓰지만 힘든 마음일 수도 있는 말: 답은 그대로 내고 끝에 상담 안내 한 문장을 붙인다 (노드 끝)
_CRISIS_WEAK = r"(죽을\s*것\s*같|우울증)"


def weak_crisis_expression(text: str) -> bool:
    """과장으로도 쓰는 힘든 마음 표현인가 (P-083). 답 끝에 상담 안내 한 문장"""
    return bool(re.search(_CRISIS_WEAK, text or ""))


def crisis_expression(text: str) -> bool:
    """마음이 크게 힘들다는 표현이 있는가 (P-075)"""
    return bool(re.search(_CRISIS, text or ""))


def trading_ask(question: str) -> bool:
    """질문이 사고팔기 판단을 묻는 꼴인가."""
    q = (question or "").strip().rstrip("?!. ")
    if re.search(_PICK, q):
        return True
    if re.search(_TERM_Q, q) or re.search(_WH, q) or re.search(_QUOTE, q):
        return False
    return bool(re.search(_DIRECT, q) or re.search(_HEARSAY, q) or re.search(_VERB + r"[가-힣\s]{0,4}?" + _ASK, q))
